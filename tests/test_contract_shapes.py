"""The seen-store fixture, and the contract that describes it.

Phase 2 of docs/PROJECT_BLUEPRINT.md established that the spec layer and the
engine use different field names for the same thing — `date` in a provider
result, `postedDate` in an engine row, `posted_date` in the seen store. A
guessed field name produces wrong data silently, so the contract
(`applyos/packages/core/src/contract.ts`) states every boundary's shape.

Two things have to hold:

  1. The fixture must round-trip through the real state engine unchanged. It
     was GENERATED by `tools/rank_state.py`, so it is the current writer's
     output by construction — a byte-stable round-trip proves the format has
     not drifted.
  2. Every key in the fixture must appear in the contract's `seenEntry`
     shape. If the writer grows a field the contract does not mention, this
     fails — which is how the contract stays true.
"""

import json
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO / "tools"))

FIXTURE = REPO / "tests" / "fixtures" / "seen_jobs.json"
CONTRACT = REPO / "applyos" / "packages" / "core" / "src" / "contract.ts"


class SeenStoreFixtureTests(unittest.TestCase):
    def test_the_fixture_exists_and_is_well_formed(self):
        self.assertTrue(FIXTURE.is_file(), f"{FIXTURE} is missing")
        doc = json.loads(FIXTURE.read_text(encoding="utf-8"))
        self.assertIn("seen", doc)
        self.assertIsInstance(doc["seen"], dict)
        self.assertTrue(doc["seen"], "the fixture has no entries")

    def test_the_fixture_round_trips_through_the_state_engine_unchanged(self):
        """A format change must not silently rewrite a candidate's history."""
        with tempfile.TemporaryDirectory() as tmp:
            state = Path(tmp) / "seen_jobs.json"
            original = FIXTURE.read_text(encoding="utf-8")
            state.write_text(original, encoding="utf-8")

            # `sweep` is the only write path that touches an entry without
            # any scoring result, so it is the cheapest way to prove the
            # loader and the writer agree with the stored format.
            result = subprocess.run(
                [sys.executable, str(REPO / "tools" / "rank_state.py"), "sweep",
                 "--state", str(state), "--today", "2026-10-13", "--write"],
                capture_output=True, text=True, cwd=str(REPO),
            )
            self.assertEqual(result.returncode, 0, result.stderr)

            after = json.loads(state.read_text(encoding="utf-8"))
            before = json.loads(original)
            # Only entries whose deadline has passed may change, and only
            # their `status`. Nothing else may move.
            for key, entry in before["seen"].items():
                self.assertIn(key, after["seen"], f"the sweep dropped {key}")
                for field, value in entry.items():
                    self.assertEqual(
                        after["seen"][key].get(field), value,
                        f"sweep changed {key}.{field}",
                    )

    def test_the_fixture_exercises_the_fields_the_contract_documents(self):
        contract = CONTRACT.read_text(encoding="utf-8")
        doc = json.loads(FIXTURE.read_text(encoding="utf-8"))
        seen_fields = set()
        for entry in doc["seen"].values():
            seen_fields.update(entry.keys())
        for field in sorted(seen_fields):
            self.assertIn(
                f'"{field}"', contract,
                f"the seen store writes '{field}' but the contract does not document it",
            )


class ContractShapeTests(unittest.TestCase):
    """The contract is read by the spec layer, so it must stay complete."""

    def setUp(self):
        self.contract = CONTRACT.read_text(encoding="utf-8")

    def test_every_boundary_shape_is_documented(self):
        for shape in ("providerEnvelope", "providerResult", "jobPosting",
                      "sourceNote", "seenEntry"):
            self.assertIn(shape, self.contract, f"the {shape} shape is not documented")

    def test_the_contract_names_the_date_field_in_every_boundary(self):
        # The whole reason the contract exists.
        self.assertIn('name: "date"', self.contract)
        self.assertIn('name: "postedDate"', self.contract)
        self.assertIn('name: "posted_date"', self.contract)

    def test_the_contract_states_that_null_means_not_stated(self):
        self.assertIn("the source did not state it", self.contract)

    def test_the_contract_points_at_the_spec_for_the_scoring_tables(self):
        self.assertIn("04-job-evaluation.md", self.contract)
        self.assertIn("spec_parity.py", self.contract)

    def test_the_contract_keeps_the_legacy_tracker_column(self):
        self.assertIn("cover_letter_file", self.contract)


if __name__ == "__main__":
    unittest.main()
