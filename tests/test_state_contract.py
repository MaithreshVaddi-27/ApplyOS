"""Tests for the seen-store contract and the compact command.

Phase 3 of docs/PROJECT_BLUEPRINT.md. Two things are tested here:

  - the STATE CONTRACT (applyos/packages/core/src/state.ts) — the format the
    engine reads, its version marker, and the legacy-location migration;
  - the COMPACT command (tools/rank_state.py) — the answer to Q9, the store
    that grows for the life of the workspace.

The compaction rule is conservative on purpose: a dropped posting is one the
candidate may see again, so nothing is dropped without a status, a date, and
an explicit --write.
"""

import json
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
TOOL = REPO / "tools" / "rank_state.py"
FIXTURE = REPO / "tests" / "fixtures" / "seen_jobs.json"


def run_tool(state: Path, *args: str) -> dict:
    # --state belongs to the subparser, so it goes AFTER the command.
    result = subprocess.run(
        [sys.executable, str(TOOL), args[0], "--state", str(state), *args[1:]],
        capture_output=True, text=True, cwd=str(REPO),
    )
    if result.returncode not in (0, 1):
        raise AssertionError(f"the tool failed: {result.returncode}\n{result.stderr}")
    return json.loads(result.stdout)


class CompactCommandTests(unittest.TestCase):
    """Q9: the store grows for the life of the workspace."""

    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)
        self.state = Path(self.tmp.name) / "seen_jobs.json"

    def write(self, seen: dict):
        self.state.write_text(json.dumps({"seen": seen}), encoding="utf-8")

    def test_compact_is_a_dry_run_by_default(self):
        self.write({"old-skipped": {"status": "skipped", "posted_date": "2020-01-01"}})
        out = run_tool(self.state, "compact", "--older-than", "90", "--today", "2026-11-13")
        self.assertEqual(out["dropped_count"], 1)
        self.assertFalse(out["written"], "compact must not write without --write")
        self.assertIn("old-skipped", json.loads(self.state.read_text())["seen"])

    def test_compact_removes_an_entry_when_written(self):
        self.write({
            "old-skipped": {"status": "skipped", "posted_date": "2020-01-01"},
            "keep-me": {"status": "ranked", "posted_date": "2020-01-01"},
        })
        out = run_tool(self.state, "compact", "--older-than", "90", "--today", "2026-11-13", "--write")
        self.assertTrue(out["written"])
        seen = json.loads(self.state.read_text())["seen"]
        self.assertNotIn("old-skipped", seen)
        self.assertIn("keep-me", seen)

    def test_compact_keeps_a_ranked_entry_however_old(self):
        """A scored posting is the candidate's record of a decision - never dropped."""
        self.write({"scored": {"status": "ranked", "posted_date": "2019-01-01"}})
        out = run_tool(self.state, "compact", "--older-than", "90", "--today", "2026-11-13")
        self.assertEqual(out["dropped_count"], 0)

    def test_compact_keeps_a_recent_entry(self):
        self.write({"recent": {"status": "skipped", "posted_date": "2026-11-01"}})
        out = run_tool(self.state, "compact", "--older-than", "90", "--today", "2026-11-13")
        self.assertEqual(out["dropped_count"], 0)

    def test_compact_keeps_an_entry_with_no_date(self):
        """Without a date there is no way to know whether the posting is still live."""
        self.write({"undated": {"status": "skipped", "posted_date": None}})
        out = run_tool(self.state, "compact", "--older-than", "90", "--today", "2026-11-13")
        self.assertEqual(out["dropped_count"], 0)

    def test_compact_keeps_an_entry_whose_deadline_is_in_the_future(self):
        self.write({"open": {"status": "skipped", "posted_date": "2020-01-01", "deadline": "2027-01-01"}})
        out = run_tool(self.state, "compact", "--older-than", "90", "--today", "2026-11-13")
        self.assertEqual(out["dropped_count"], 0)

    def test_compact_keeps_an_excluded_entry(self):
        self.write({"pinned": {"status": "skipped", "posted_date": "2020-01-01"}})
        out = run_tool(self.state, "compact", "--older-than", "90", "--today", "2026-11-13",
                       "--exclude", "pinned")
        self.assertEqual(out["dropped_count"], 0)

    def test_compact_drops_an_expired_entry_with_a_passed_deadline(self):
        self.write({"gone": {"status": "expired", "posted_date": "2020-01-01", "deadline": "2021-01-01"}})
        out = run_tool(self.state, "compact", "--older-than", "90", "--today", "2026-11-13")
        self.assertEqual(out["dropped_count"], 1)


class SeenStoreContractTests(unittest.TestCase):
    """The fixture is generated by the real writer, so it pins the real format."""

    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)
        self.state = Path(self.tmp.name) / "seen_jobs.json"
        self.state.write_text(FIXTURE.read_text(encoding="utf-8"), encoding="utf-8")

    def test_the_tool_reads_the_fixture_without_error(self):
        out = run_tool(self.state, "candidates", "--limit", "10")
        self.assertEqual(out["total_entries"], 3, "the fixture's three entries were not read")

    def test_the_fixture_survives_a_sweep_unchanged(self):
        """Sweep may only retire an entry whose deadline passed. Nothing else moves."""
        before = json.loads(self.state.read_text(encoding="utf-8"))
        run_tool(self.state, "sweep", "--today", "2026-11-13", "--write")
        after = json.loads(self.state.read_text(encoding="utf-8"))
        for key, entry in before["seen"].items():
            self.assertIn(key, after["seen"], f"sweep dropped {key}")
            for field, value in entry.items():
                if field == "status":
                    # The one field sweep may change: ranked -> expired.
                    self.assertIn(after["seen"][key].get(field), (value, "expired"))
                    continue
                self.assertEqual(after["seen"][key].get(field), value, f"{key}.{field} moved")

    def test_the_tool_reads_the_bare_map_shape_too(self):
        """An older store may be the map itself, with no `seen` wrapper."""
        doc = json.loads(self.state.read_text(encoding="utf-8"))
        self.state.write_text(json.dumps(doc["seen"]), encoding="utf-8")
        out = run_tool(self.state, "candidates", "--limit", "10")
        self.assertEqual(out["total_entries"], 3, "the bare-map shape was not read")

    def test_a_non_object_entry_is_reported_not_crashed(self):
        doc = json.loads(self.state.read_text(encoding="utf-8"))
        doc["seen"]["broken"] = "not an object"
        self.state.write_text(json.dumps(doc), encoding="utf-8")
        result = subprocess.run(
            [sys.executable, str(TOOL), "candidates", "--state", str(self.state)],
            capture_output=True, text=True, cwd=str(REPO),
        )
        self.assertNotEqual(result.returncode, 0)
        self.assertIn("not an object", result.stderr + result.stdout)


if __name__ == "__main__":
    unittest.main()
