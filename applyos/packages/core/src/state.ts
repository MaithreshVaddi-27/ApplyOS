//
// The seen-store contract.
//
// `workspace/seen_jobs.json` is the pipeline's memory: every posting ever
// seen, with its scores, verdicts, and deadlines. It is append-only by
// design, and it is the candidate's own data - so the contract for it has to
// be explicit rather than implied by whatever the writer happened to emit.
//
// This module is the TypeScript side of that contract. The Python side is
// tools/rank_state.py, which is the spec's own state engine and owns the
// writes today. Both read the same shape, and a fixture generated by the
// real writer pins it.
//
// Versioning:
//   - `SEEN_STORE_VERSION` is the version this module reads and writes.
//   - A store without a version marker is version 1 - the format that has
//     always existed. The marker is ADDITIVE: it never invalidates an
//     existing store.
//   - `migrate` applies the known migrations in order. Today that is the
//     legacy-location normalisation: an early store kept a verdict in the
//     `location` field, which then read as a place.

import { existsSync, readFileSync, renameSync, unlinkSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";

/** The version this module reads and writes. */
export const SEEN_STORE_VERSION = 1;

/** One posting's stored state. */
export interface SeenEntry {
  title?: string;
  company?: string;
  /** The posting's place. Not a verdict. */
  location?: string | null;
  url?: string;
  portal?: string;
  /** ISO date. snake_case here, unlike the provider result's `date`. */
  posted_date?: string | null;
  /** seen | scored | ranked | skipped | expired */
  status?: string;
  scores?: Record<string, number>;
  rank_score?: number;
  rank_verdict?: string;
  rank_date?: string;
  rank_history?: { score: number; verdict?: string; date?: string }[];
  location_verdict?: string;
  language_gate?: string;
  language_note?: string;
  deadline?: string | null;
  strengths?: string[];
  gaps?: string[];
  [key: string]: unknown;
}

/** The whole store. */
export interface SeenStore {
  /** Added in version 1. A store without it is still version 1. */
  schemaVersion?: number;
  seen: Record<string, SeenEntry>;
}

const VERDICTS = new Set(["PASS", "FAIL", "FLAG"]);

/**
 * The legacy-location migration.
 *
 * An early store kept a location verdict in the `location` field, so
 * `location` could hold "PASS" instead of a place. The verdict belongs in
 * `location_verdict`; the place belongs in `location`.
 */
export function normaliseLegacyLocation(entry: SeenEntry): SeenEntry {
  if (typeof entry.location === "string" && VERDICTS.has(entry.location)) {
    const { location, ...rest } = entry;
    return {
      ...rest,
      location_verdict: entry.location_verdict ?? location,
    };
  }
  return entry;
}

/** Apply the known migrations up to `toVersion`. */
export function migrate(store: SeenStore, toVersion: number = SEEN_STORE_VERSION): SeenStore {
  if (toVersion > SEEN_STORE_VERSION) {
    throw new Error(
      `cannot migrate the seen store to version ${toVersion}: this build knows version ${SEEN_STORE_VERSION}`,
    );
  }
  const from = store.schemaVersion ?? 1;
  if (from > SEEN_STORE_VERSION) {
    throw new Error(
      `the seen store is version ${from}, but this build only understands version ${SEEN_STORE_VERSION}. ` +
        "A newer ApplyOS wrote it - update before reading.",
    );
  }
  const seen: Record<string, SeenEntry> = {};
  for (const [key, entry] of Object.entries(store.seen ?? {})) {
    seen[key] = normaliseLegacyLocation(entry);
  }
  return { ...store, schemaVersion: SEEN_STORE_VERSION, seen };
}

/** Read and migrate a store. Returns an empty store when the file is absent. */
export function readSeenStore(path: string): SeenStore {
  if (!existsSync(path)) return { schemaVersion: SEEN_STORE_VERSION, seen: {} };
  let parsed: unknown;
  try {
    parsed = JSON.parse(readFileSync(path, "utf8"));
  } catch (e) {
    throw new Error(`the seen store is not valid JSON: ${e instanceof Error ? e.message : String(e)}`);
  }
  const doc = (parsed ?? {}) as SeenStore;
  // A store may be the bare map (older shape) or the {seen: {...}} wrapper.
  const seen = (doc.seen && typeof doc.seen === "object" ? doc.seen : (doc as unknown as Record<string, SeenEntry>)) ?? {};
  return migrate({ ...doc, seen } as SeenStore);
}

/**
 * Write a store atomically.
 *
 * A half-written seen_jobs.json loses the candidate's entire search history,
 * so the file is written beside the target and renamed over it.
 */
export function writeSeenStore(path: string, store: SeenStore): void {
  const doc = { schemaVersion: SEEN_STORE_VERSION, ...store, seen: store.seen ?? {} };
  const tmp = `${path}.tmp`;
  writeFileSync(tmp, JSON.stringify(doc, null, 2) + "\n", "utf8");
  try {
    renameSync(tmp, path);
  } catch {
    // Windows can refuse a rename onto an existing file. The store still has
    // to be written, so fall back to a direct write and drop the temp file.
    writeFileSync(path, JSON.stringify(doc, null, 2) + "\n", "utf8");
    try {
      unlinkSync(tmp);
    } catch {
      /* a leftover temp file is harmless; the store itself is written */
    }
  }
}

/** The entries a store holds, in insertion order. */
export function entries(store: SeenStore): [string, SeenEntry][] {
  return Object.entries(store.seen ?? {});
}
