"""Phase 9.1: the corpus is well-formed, redacted and provenance-tagged."""

import json
import unittest
from pathlib import Path

CORPUS = Path(__file__).resolve().parent.parent / "applyos" / "evals" / "corpus"


class CorpusTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.manifest = json.loads((CORPUS / "MANIFEST.json").read_text(encoding="utf-8"))
        cls.rubric = (CORPUS / "RUBRIC.md").read_text(encoding="utf-8")
        cls.suites = {
            name: json.loads((CORPUS / filename).read_text(encoding="utf-8"))
            for name, filename in cls.manifest["suites"].items()
        }

    def test_the_manifest_is_versioned_and_names_every_suite(self):
        self.assertEqual(1, self.manifest["schemaVersion"])
        self.assertEqual({"gates", "dedupe", "documents", "ranking"}, set(self.manifest["suites"]))
        self.assertTrue((CORPUS / self.manifest["rubric"]).is_file())

    def test_the_rubric_precedes_the_labels(self):
        # The rubric is committed with the corpus and states its own creation
        # order — a corpus generated by the evaluated code would have no rubric.
        self.assertIn("committed before any label", self.rubric)
        self.assertIn("derived by running gates", self.rubric)
        self.assertIn("candidate", self.rubric)

    def test_every_item_has_provenance_and_a_label_method(self):
        for name, items in self.suites.items():
            self.assertGreaterEqual(len(items), 3, f"{name} corpus is too small to measure")
            for item in items:
                with self.subTest(suite=name, id=item.get("id")):
                    self.assertIn("source", item, f"{item.get('id')} has no source")
                    for field in ("portal", "url", "captured"):
                        self.assertIn(field, item["source"], f"{item.get('id')} source lacks {field}")
                    labels = item["labels"]
                    self.assertIn("labelMethod", labels, f"{item.get('id')} has no label method")
                    self.assertIn(labels["labelMethod"], self.manifest["labelMethods"])
                    self.assertIn("labelledBy", labels)
                    self.assertIn("rationale", labels)

    def test_items_are_redacted(self):
        # No full third-party posting is redistributed: descriptions are short
        # and every URL uses the redacted.example placeholder host.
        for item in self.suites["gates"]:
            self.assertLess(len(item["description"]), 300, f"{item['id']} has a full posting")
            self.assertIn("redacted.example", item["posting"]["url"])
        for item in self.suites["dedupe"]:
            for row in item["pair"].values():
                self.assertEqual(8, len(row), f"{item['id']} carries more than the eight JobPosting fields")

    def test_dedupe_probes_all_three_requisition_edges(self):
        kinds = {item["kind"] for item in self.suites["dedupe"]}
        for kind in ("shared-id-different-company", "different-ids-same-company", "date-shaped-segment"):
            self.assertIn(kind, kinds)

    def test_the_corpus_is_not_generated_by_the_evaluated_code(self):
        # The label method is a rule from RUBRIC.md, not a runner invocation.
        text = "\n".join(
            p.read_text(encoding="utf-8") for p in CORPUS.glob("*.json")
        )
        for banned in ("runGates(", "collapseReqSpread(", "scorePosting("):
            self.assertNotIn(banned, text, f"corpus contains an evaluated-code call: {banned}")


if __name__ == "__main__":
    unittest.main()
